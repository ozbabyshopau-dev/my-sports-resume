const DEFAULT_AVAILABILITY = {
  openToTrials: false,
  openToAcademy: false,
  openToSchoolSport: false,
  openToRepresentativePathways: false,
  openToSeniorSigning: false,
  openToFirstGrade: false,
  openToReserveGrade: false,
  willingToRelocate: false,
  preferredLocations: "",
};

const DEFAULT_PHYSICAL_DETAILS = {
  height: "",
  weight: "",
  dominantSide: "",
  preferredSide: "",
  fitnessNotes: "",
  speedMetrics: "",
};

const DEFAULT_PLAYING_HISTORY = {
  currentTeam: "",
  previousTeams: [],
  yearsPlayed: "",
  mainCompetition: "",
  representativeHistory: [],
  schoolHistory: [],
  academyHistory: [],
};

const DEFAULT_ACHIEVEMENT_SECTIONS = {
  awards: [],
  representativeSelections: [],
  finalsHistory: [],
  mvpAwards: [],
  bestAndFairest: [],
  carnivalResults: [],
  otherAchievements: [],
};

function cleanList(items = []) {
  return items.filter(Boolean);
}

function buildAvailability(overrides = {}) {
  return {
    ...DEFAULT_AVAILABILITY,
    ...overrides,
  };
}

function buildPhysicalDetails(overrides = {}) {
  return {
    ...DEFAULT_PHYSICAL_DETAILS,
    ...overrides,
  };
}

function buildPlayingHistory(overrides = {}) {
  return {
    ...DEFAULT_PLAYING_HISTORY,
    ...overrides,
    previousTeams: cleanList(overrides.previousTeams),
    representativeHistory: cleanList(overrides.representativeHistory),
    schoolHistory: cleanList(overrides.schoolHistory),
    academyHistory: cleanList(overrides.academyHistory),
  };
}

function buildAchievementSections(overrides = {}) {
  return {
    awards: cleanList(overrides.awards),
    representativeSelections: cleanList(overrides.representativeSelections),
    finalsHistory: cleanList(overrides.finalsHistory),
    mvpAwards: cleanList(overrides.mvpAwards),
    bestAndFairest: cleanList(overrides.bestAndFairest),
    carnivalResults: cleanList(overrides.carnivalResults),
    otherAchievements: cleanList(overrides.otherAchievements),
  };
}

function flattenAchievementSections(sections) {
  return Object.values(sections).flat().filter(Boolean);
}

function buildReferences(overrides = {}) {
  return {
    coachName: overrides.coachName || "",
    coachRole: overrides.coachRole || "",
  };
}

function buildAthlete(profile) {
  const achievementSections = buildAchievementSections(profile.achievementSections);

  return {
    ...profile,
    secondaryPosition: profile.secondaryPosition || "",
    clubEntryType: profile.clubEntryType || "custom",
    isVerifiedClubEntry:
      typeof profile.isVerifiedClubEntry === "boolean" ? profile.isVerifiedClubEntry : false,
    verificationBadges: profile.verificationBadges || [],
    stats: profile.stats || [],
    highlights: profile.highlights || [],
    contactRoute: profile.contactRoute || (profile.isJunior ? "parent_guardian" : "athlete"),
    physicalDetails: buildPhysicalDetails(profile.physicalDetails),
    playingHistory: buildPlayingHistory(profile.playingHistory),
    achievementSections,
    achievements: flattenAchievementSections(achievementSections),
    references: buildReferences(profile.references),
    availability: buildAvailability(profile.availability),
  };
}

function buildHighlight(highlight) {
  return {
    highlightType: "Match highlight",
    eventName: "",
    eventDate: "",
    videoUrl: "",
    verificationStatus: highlight.isJunior ? "Parent approval needed" : "Pending review",
    tag: "Rising Highlight",
    boostCount: 0,
    isBoosted: false,
    visibilityStatus: "Pending Verification",
    ...highlight,
  };
}

